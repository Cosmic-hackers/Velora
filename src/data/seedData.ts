export interface Category {
  id: string;
  name: string;
  slug: string;
  description: string;
  imageUrl: string;
  displayOrder: number;
  department?: 'women' | 'men' | 'accessories' | 'all';
}

export interface Collection {
  id: string;
  name: string;
  slug: string;
  description: string;
  imageUrl: string;
  isFeatured: boolean;
  displayOrder: number;
}

export interface ColorOption {
  name: string;
  hex: string;
  imageUrl?: string;
}

export interface ProductVariant {
  id: string;
  productId: string;
  size: string;
  color: string;
  sku: string;
  price: number;
  stock: number;
}

export interface Product {
  id: string;
  name: string;
  slug: string;
  sku: string;
  description: string;
  details: string[];
  fabricCare?: string[];
  fitInfo?: string[];
  price: number; // in INR / base units (e.g., 18500 = ₹18,500)
  salePrice?: number | null;
  categoryId: string;
  categoryName?: string;
  department?: 'women' | 'men' | 'accessories';
  collectionId: string;
  collectionName?: string;
  gender: 'men' | 'women' | 'unisex';
  sizes: string[];
  colors: ColorOption[];
  images: string[];
  isFeatured: boolean;
  isNewArrival: boolean;
  isBestSeller?: boolean;
  isPublished: boolean;
  rating: number;
  reviewCount: number;
  completeLookProductIds?: string[];
  createdAt: string;
}

export interface Review {
  id: string;
  productId: string;
  userId: string;
  userName: string;
  rating: number;
  title: string;
  comment: string;
  isVerifiedPurchase: boolean;
  status: 'pending' | 'approved' | 'rejected';
  createdAt: string;
}

export interface Coupon {
  id: string;
  code: string;
  discountType: 'percentage' | 'fixed';
  discountValue: number;
  minOrderValue: number;
  maxDiscount?: number;
  usageLimit?: number;
  timesUsed: number;
  isActive: boolean;
  expiresAt?: string;
}

export interface OrderItem {
  id: string;
  productId: string;
  productName: string;
  price: number;
  quantity: number;
  size: string;
  color: string;
  imageUrl: string;
}

export interface Order {
  id: string;
  orderNumber: string;
  userId?: string | null;
  customerName: string;
  customerEmail: string;
  customerPhone: string;
  shippingAddress: {
    addressLine: string;
    apartmentSuite?: string;
    city: string;
    state: string;
    postalCode: string;
    country: string;
  };
  subtotal: number;
  discount: number;
  shippingCost: number;
  totalAmount: number;
  paymentMethod: 'razorpay' | 'cod';
  paymentStatus: 'pending' | 'paid' | 'failed';
  orderStatus: 'pending' | 'confirmed' | 'processing' | 'shipped' | 'delivered' | 'cancelled' | 'return_requested' | 'returned';
  trackingNumber?: string;
  trackingCarrier?: string;
  cancellationReason?: string;
  returnReason?: string;
  createdAt: string;
  items: OrderItem[];
}

